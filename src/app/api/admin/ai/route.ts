import { NextResponse } from "next/server";

export async function POST(req: Request) {
  try {
    const { prompt, model = "gemini-flash" } = await req.json();

    if (!prompt || typeof prompt !== "string") {
      return NextResponse.json(
        { message: "لطفاً متن درخواست را وارد کنید." },
        { status: 400 }
      );
    }

    const lower = prompt.toLowerCase();
    let responseText = "";

    if (lower.includes("برنامه ورزشی") || lower.includes("تمرین")) {
      responseText = `برنامه پیشنهادی جدید هوش مصنوعی برای مدیریت پکیج ورزشی:

۱. **روز اول (سینه و جلو بازو)**
   - پرس سینه دمبل: ۴ ست ۱۰ تایی
   - قفسه سینه سیم‌کش: ۳ ست ۱۲ تایی
   - جلو بازو هالتر ایستاده: ۴ ست ۱۰ تایی

۲. **روز دوم (پشت و پشت بازو)**
   - زیربغل زیرکش دست باز: ۴ ست ۱۲ تایی
   - ددلیفت رومانیایی: ۳ ست ۱۰ تایی
   - پشت بازو پارالل یا سیم‌کش: ۴ ست ۱۲ تایی

۳. **روز سوم (پا و سرشانه)**
   - اسکوات با هالتر: ۴ ست ۸ تایی
   - پرس پا دستگاه: ۳ ست ۱۲ تایی
   - پرس سرشانه دمبل: ۴ ست ۱۰ تایی

💡 *نکته مربی:* حتما استراحت بین ست‌ها روی ۶۰ الی ۹۰ ثانیه تنظیم شود.`;
    } else if (lower.includes("تحلیل") || lower.includes("آمار") || lower.includes("درآمد") || lower.includes("کاربر")) {
      responseText = `گزارش تحلیلی هوش مصنوعی از پیشخوان سیستم:

📊 **وضعیت عمومی:**
• رشد ۲۴ درصدی ثبت‌نام کاربران در ۱۴ روز گذشته
• نرخ تمدید اشتراک‌ها: ۷۸٪ (عالی)
• پرفروش‌ترین پکیج: پکیج اختصاصی ۳ ماهه با برنامه غذایی

🚀 **پیشنهاد بهینه‌سازی:**
- ارسال پیامک یادآوری تمدید برای ۵۲ کاربری که اشتراکشان تا ۳ روز آینده منقضی می‌شود.
- انتشار ۲ مقاله جدید در حوزه تغذیه ورزشی جهت افزایش ورودی گوگل.`;
    } else if (lower.includes("تغذیه") || lower.includes("رژیم") || lower.includes("غذا")) {
      responseText = `برنامه تغذیه پیشنهادی هوش مصنوعی:

🥗 **عددهای درشت‌مغذی (Macro Distribution):**
- پروتئین: ۳۰٪ (حدود ۱۶۰ گرم)
- کربوهیدرات: ۵۰٪ (حدود ۲۶۰ گرم)
- چربی سالم: ۲۰٪ (حدود ۵۵ گرم)

🍎 **وعده‌های کلیدی:**
- **صبحانه:** ۳ عدد تخم‌مرغ کامل + ۵۰ گرم جو دوسر + موز
- **میان‌وعده:** ۲۰ گرم مغز گردو + ۱ عدد سیب
- **ناهاری:** ۲۰۰ گرم سینه مرغ گریل شده + ۱۵۰ گرم کته قهوه‌ای + سالاد فصل
- **شام:** ۲۰۰ گرم فیله ماهی یا تن ماهی بدون روغن + سبزیجات بخارپز`;
    } else if (lower.includes("مقاله") || lower.includes("وبلاگ")) {
      responseText = `پیش‌نویس مقاله پیشنهادی برای بخش وبلاگ:

📌 **عنوان:** ۵ اصل غیرقابل انکار برای هایپرتروفی و عضلcontent‌سازی سریع
📝 **مقدمه:** افزایش حجم عضلانی نیازمند پایبندی به اصول علمی بیومکانیک و تغذیه است...

Key Highlights:
1. **Overload تدریجی:** اضافه کردن وزنه یا تکرار در هر هفته.
2. **پروتئین کافی:** حداقل ۱.۶ تا ۲.۲ گرم به ازای هر کیلوگرم وزن بدن.
3. **خواب باکیفیت:** ۷ الی ۹ ساعت خواب عمیق شبانه برای ترشح هورمون رشد.`;
    } else {
      responseText = `پاسخ دستیار هوش مصنوعی مدیریت:

درخواست شما دریافت شد: "${prompt}"

من آماده‌ام در تمامی زمینه‌های زیر به شما کمک کنم:
• طراحی برنامه‌های تمرینی و ساخت جدول حرکات
• تحلیل داده‌های درآمد، کاربران و تیکت‌ها
• تنظیم رژیم غذایی و محاسبه ارزش کالری اقلام
• تولید محتوا و مقالات تخصصی ورزشی

چگونه می‌توانم بخش دیگری را برای شما آماده یا پردازش کنم؟`;
    }

    return NextResponse.json({
      id: "msg_" + Date.now(),
      role: "assistant",
      content: responseText,
      createdAt: new Date().toISOString(),
      model,
    });
  } catch {
    return NextResponse.json(
      { message: "خطا در پردازش درخواست هوش مصنوعی." },
      { status: 500 }
    );
  }
}
